// Helper to safely load / save CMS state from localStorage
const STORAGE_KEY = "mannat_arts_cms_store_v2";

export function loadCMSStore(): CMSDataStore {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      return {
        homepage: parsed.homepage || INITIAL_HOMEPAGE_CONFIG,
        experiences: parsed.experiences || INITIAL_EXPERIENCES,
        artists: parsed.artists || ALL_ARTISTS,
        genres: parsed.genres || GENRE_METADATA,
        moods: parsed.moods || INITIAL_MOODS,
        occasions: parsed.occasions || INITIAL_OCCASIONS,
        articles: parsed.articles || BLOG_ARTICLES,
        testimonials: parsed.testimonials || INITIAL_TESTIMONIALS,
        media: parsed.media || INITIAL_MEDIA_LIBRARY,
        navigation: parsed.navigation || INITIAL_NAV_LINKS,
        footer: parsed.footer || INITIAL_FOOTER_CONFIG,
        seo: parsed.seo || INITIAL_SEO_CONFIG,
        settings: parsed.settings || INITIAL_SETTINGS,
        users: parsed.users || INITIAL_CMS_USERS,
        activityLog: parsed.activityLog || INITIAL_ACTIVITY_LOG,
        recommendationOverrides: parsed.recommendationOverrides || [],
      };
    }
  } catch (err) {
    console.error("Error loading CMS store:", err);
  }

  return {
    homepage: INITIAL_HOMEPAGE_CONFIG,
    experiences: INITIAL_EXPERIENCES,
    artists: ALL_ARTISTS,
    genres: GENRE_METADATA,
    moods: INITIAL_MOODS,
    occasions: INITIAL_OCCASIONS,
    articles: BLOG_ARTICLES,
    testimonials: INITIAL_TESTIMONIALS,
    media: INITIAL_MEDIA_LIBRARY,
    navigation: INITIAL_NAV_LINKS,
    footer: INITIAL_FOOTER_CONFIG,
    seo: INITIAL_SEO_CONFIG,
    settings: INITIAL_SETTINGS,
    users: INITIAL_CMS_USERS,
    activityLog: INITIAL_ACTIVITY_LOG,
    recommendationOverrides: [],
  };
}

export function saveCMSStore(store: CMSDataStore): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(store));
  } catch (err) {
    console.error("Error saving CMS store:", err);
  }
}

export function resetCMSStore(): CMSDataStore {
  try {
    localStorage.removeItem(STORAGE_KEY);
  } catch {}
  return loadCMSStore();
}
